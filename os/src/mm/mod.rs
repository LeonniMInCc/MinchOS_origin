//! 内存管理子系统。
//!
//! - **第 2 周（现在）**：只有内核堆。让内核自己能用上动态数据结构。
//! - 第 6 周：页帧分配器 + 多级页表
//! - 第 7 周：地址空间抽象，开启 SV39 分页
//!
//! 注意区分两件事：本模块的**内核堆**管的是内核自己的小块内存（进程表、
//! 页表项数组这类元数据）；第 6 周的**页帧分配器**管的是整个物理内存的
//! 4 KiB 页，那是要分给用户进程用的。两者在地址空间里互不重叠。

mod heap_allocator;

pub use heap_allocator::heap_test;

/// 初始化内存管理子系统。
///
/// 必须在 `clear_bss()` 之后调用 —— 堆空间就在 `.bss` 里。
pub fn init() {
    heap_allocator::init();
}
