//! 恶意程序之三：往一个不存在的地址写数据。
//!
//! 预期结果：CPU 抛出 StoreFault 异常，内核捕获后杀掉这个程序。
//!
//! # 一个不舒服的事实
//!
//! 这个程序能被拦住，靠的是"地址 0 在 QEMU virt 的物理内存图上不存在"，
//! 而**不是**因为内核保护了自己。
//!
//! 本章没有分页，用户程序拿到的就是真实物理地址。如果它往
//! `0x80200000`（内核代码段）写，硬件不会有任何意见 —— 内核会被
//! 悄无声息地改写。
//!
//! 这就是第 7–8 周必须引入分页的原因：只有建立起地址空间隔离，
//! "用户程序碰不到内核"才会从一句口号变成硬件保证。

#![no_std]
#![no_main]

#[macro_use]
extern crate user_lib;

#[no_mangle]
pub fn main() -> i32 {
    println!("我要往地址 0x0 写一个字节。");

    unsafe {
        (0x0 as *mut u8).write_volatile(0x42);
    }

    println!("如果你看到这行，说明写成功了 —— 那说明地址 0 是可写的。");
    -1
}
