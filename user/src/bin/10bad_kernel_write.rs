//! 恶意程序之四：直接往**内核代码段**写数据。
//!
//! 这个程序是第 7 周的核心演示。同一份代码，在不同的章节里结局完全不同：
//!
//! | 章节 | 结局 |
//! |---|---|
//! | 第 3–6 周 | **写成功**。没有分页，用户程序拿到的是真实物理地址，
//!   硬件不会有任何意见 —— 内核被悄无声息地改写 |
//! | 第 7 周起 | 触发 StorePageFault。内核的页不带 `U` 位，
//!   MMU 在用户态访问时直接拒绝 |
//!
//! 注意它和 `07bad_syscall_arg` 的区别：那个是把内核地址当作**系统调用
//! 参数**递进去（访存由内核自己完成，MMU 会放行，只能靠软件检查拦），
//! 这个是**直接解引用**（访存由用户态完成，MMU 说了算）。
//!
//! 两条路都得堵上，缺一不可。

#![no_std]
#![no_main]

#[macro_use]
extern crate user_lib;

/// 内核代码段的起始地址。用户程序本来完全不该知道、更不该碰这个地址。
const KERNEL_TEXT: usize = 0x8020_0000;

#[no_mangle]
pub fn main() -> i32 {
    println!("  [越权] 我要直接往内核代码段 {:#x} 写一个字节。", KERNEL_TEXT);
    println!("  [越权] 第 6 周之前这会成功，而且内核不会察觉。");

    unsafe {
        (KERNEL_TEXT as *mut u8).write_volatile(0x42);
    }

    println!("  [越权] 如果你看到这行，说明内存隔离没生效 —— 那是严重问题。");
    -1
}
